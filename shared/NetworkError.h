#pragma once

// Ошибки транспорта — общий для клиента и сервера перечислитель: обе стороны
// обязаны одинаково называть одно и то же, иначе событие на клиенте и запись
// в логе сервера расскажут про одну аварию разные истории.
//
// Важное следствие ZeroMQ: отдельного кода «пир пропал» практически не
// бывает — умерший собеседник просто перестаёт отвечать, и приём возвращает
// EAGAIN, то есть таймаут (см. тест TransportEcho: там сервер закрывается
// прямо под клиентом, а клиент всё равно получает Timeout). Поэтому в
// клиенте и таймаут, и обрыв ведут в одно событие CONNECTION_LOST и в одну
// ошибку NETWORK_ERROR: приложение от различий не выигрывает, а цена
// разделения — две почти одинаковые ветки в диспетчере.

enum class NetworkError
{
    Ok,            // операция прошла успешно
    Timeout,       // истёк таймаут приёма или отправки: пир не ответил вовремя
    NotConnected,  // сокета нет: не вызван connect()/listen() либо он уже
                   // закрыт после предыдущей ошибки
    SocketError    // zmq отказал в самом действии: обрыв соединения,
                   // нарушение очерёдности REQ/REP (EFSM), ошибки сокета
};

// Короткое имя для логов, вывода тестов и сообщений об ошибках. Функция
// constexpr — определяется в каждом TU отдельно, отдельный .cpp не нужен.
constexpr const char* networkErrorName(NetworkError error)
{
    switch (error)
    {
        case NetworkError::Ok:           return "ok";
        case NetworkError::Timeout:      return "timeout";
        case NetworkError::NotConnected: return "not connected";
        case NetworkError::SocketError:  return "socket error";
    }

    return "unknown";
}
