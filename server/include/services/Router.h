#pragma once

#include <string>
#include <utility>

// П.8: промежуточное принятие решения между полученным текстом и
// исполнителем. Две чистые функции, без состояния и без абстракций:
//
//     classify(text)              -> {Intent, Params}
//     executorFor(intent, params) -> Executor
//
// Вход — СЫРОЙ текст после первичной обработки: нормализация входа —
// работа исполнителя, не роутера (иначе внутри роутера вырастет switch
// по исполнителям с их форматами — вернёмся к сплетённой связке).
//
// Шов под decision-engine (JEV/LAYA, struct.txt): подменяется целиком
// classify(). Абстрактный класс с наследниками под ещё не существующий
// движок не строится — интерфейс появится со второй реализацией.
namespace Router
{
    // Намерения ТОЛЬКО те, у которых есть исполнитель: значение
    // добавляется вместе с исполнителем в одном коммите. NOTE, REMINDER,
    // PERIPHERAL, PICTURE, BINARY отложены до появления своих подсистем.
    enum class Intent
    {
        Translator,       // получить перевод
        LocalAssistant,   // ответить на вопрос (дефолт, как раньше)
    };

    // Параметры запроса. Языков в протоколе нет (поля в Request/Response
    // не добавляем): целевой язык извлекается правилами из текста.
    struct Params
    {
        std::string targetLang;   // ISO-639-1, "" — не извлечён
    };

    enum class Executor
    {
        None,             // решения нет -> фолбэк в LocalAssistant
        LocalAssistant,   // ответить на вопрос
        Translator,       // перевод, ru<->en на локальной LLM
        RemoteTranslator, // NetAssistant, пока заглушка с ошибкой
    };

    // Правила: ключевые слова + словарь языков (~20), дефолт
    // LOCAL_ASSISTANT. Классификатор на LLM — второй roundtrip на каждый
    // запрос: вернёмся, когда правила перестанут справляться.
    std::pair<Intent, Params> classify(const std::string& text);

    // Наивный switch: ru<->en -> локальный, иначе -> удалённый.
    // shortcut: потолок — второй параметр в Params или capability-правило
    // (несколько исполнителей на одно намерение): switch разрастётся в
    // матрицу с приоритетами. Upgrade — таблица (intent, guard) -> executor
    // внутри этих же двух функций; сигнатура не меняется, вызывающие не
    // трогаются. Раньше триггера не рефакторить.
    Executor executorFor(Intent intent, const Params& params);
}
